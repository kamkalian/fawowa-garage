export const LANGS = ['de', 'en'];

export function t(lang, key, ...args) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.de[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)] ?? ''));
}

/** Text aus einem { de, en }-Objekt in der Sprache; fehlt die Übersetzung, gilt Deutsch */
export function pick(obj, lang) {
  if (!obj) return '';
  return obj[lang] || obj.de || '';
}

export function zahlText(lang, n) {
  return new Intl.NumberFormat(lang, { maximumFractionDigits: 2 }).format(n);
}
